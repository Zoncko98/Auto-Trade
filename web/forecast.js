"use strict";
// Forecast is independent read-only research. No trading, brokerage or credential APIs.
function forecastNode(tag,text,cls) {
  const el=document.createElement(tag);
  if(text!==undefined && text!==null) el.textContent=String(text);
  if(cls)el.className=cls;
  return el;
}
function addForecastRow(parent,label,value){
  const row=forecastNode("div",null,"readiness-item");
  row.appendChild(forecastNode("span",label));
  row.appendChild(forecastNode("strong",value));
  parent.appendChild(row);
}
async function loadForecast(){
  const grid=document.getElementById("forecast-grid");
  const message=document.getElementById("forecast-generated");
  const overview=document.getElementById("forecast-overview");
  if(!grid)return;
  message.textContent="Loading last completed forecast from the research workstation…";
  const connection=document.getElementById("forecast-connection-state");
  grid.replaceChildren();
  try {
    const status=await request("/api/research/forecast/connection");
    if(connection)connection.textContent=(status.connected?
      "Research service connected ("+status.source+") at "+status.service_url+
      " · "+status.message :
      "Research service not connected: "+status.message);
  }catch(_){if(connection)connection.textContent="Unable to check research service status.";}
  let data;
  try{
    data=await request("/api/research/forecast");
  }catch(err){
    message.textContent="Forecast unavailable";
    overview.textContent=(err?.message||"The forecasting service cannot be reached.")+
      " Open Profile → Integrations to test its private-LAN address, normally port 8766. The research service must be installed and running separately on your AI computer.";
    return;
  }
  const live=await request("/api/research/market").catch(()=>({status:"unavailable"}));
  grid.replaceChildren();
  if(!Array.isArray(data.candidates)){
    message.textContent=data.message||"No completed forecast";
    overview.textContent="The research service is reachable, but the first forecast has not completed. Forecasts are generated by the separate AI workstation; its models may be downloading or processing data. Check its health page and logs.";
    return;
  }
  const native=data.engine==="built_in" || data.research_mode==="built_in";
  message.textContent="Generated "+formatBrokerDate(data.generated_at)+
    (native?" · NAS built-in daily-bar research":" · Next NYSE opening "+formatBrokerDate(data.target_session_open));
  if(native){
    overview.textContent="NAS-native forecast — no specialized model installation needed. "+
      (data.ranking_method||"Technical scoring")+" · "+
      (data.symbols_with_data||0)+" securities qualified from "+
      (data.universe_size||0)+" monitored. "+
      (data.connection_note||"")+
      " Illustrative price ranges use historical volatility and are NOT calibrated predictions. "+
      (data.snapshot_stale?"Snapshot is stale; refreshing in background. ":"")+
      "Live broker orders are never authorized by this research.";
  }else{
    const ok=Boolean(data.lightgbm_validation&&data.lightgbm_validation.beats_zero_return_baseline);
    overview.textContent=(ok?"LightGBM passed initial holdout, but remains experimental. ":
        "LightGBM did NOT beat its holdout baseline; predictions excluded from candidate ranking. ")+
        (data.ranking_method||"")+" · "+data.symbols_with_data+" securities analyzed. "+
        "Chronos retrospective scorecard: "+(data.model_calibration?.scored_predictions||0)+
        " completed predictions; "+(data.model_calibration?.status||"not available")+
        (data.model_calibration?.mean_absolute_log_return_error!=null?
          "; mean absolute log-return error "+data.model_calibration.mean_absolute_log_return_error:"")+
        ". Performance does not imply trade profitability.";
  }
  data.candidates.forEach((item,i)=>{
    const card=forecastNode("div",null,"panel");
    card.style.margin="16px 0";card.style.padding="18px";
    card.appendChild(forecastNode("h2","#"+(i+1)+" · "+item.ticker));
    const close=item.reference_close;
    const intro=forecastNode("p","Last historical close: "+money(close)+" on "+item.as_of+" · ");
    const market=forecastNode("a","Source: Yahoo historical chart");
    market.href="https://finance.yahoo.com/quote/"+encodeURIComponent(item.ticker)+"/history/";
    market.target="_blank";market.rel="noopener noreferrer";
    intro.appendChild(market);card.appendChild(intro);
    const ch=native?(item.historical_volatility_scenario||{}):(item.chronos_bolt||{});
    const scenario=native?ch.close_range:ch.scenario_close_range;
    const range=Array.isArray(scenario)?
        scenario.map(x=>money(x)).join(" / "):"Unavailable";
    addForecastRow(card,native?"Historical daily-volatility band (illustrative, not a forecast)":
      "Chronos-Bolt lower / median / upper scenario",range);
    if(native){
      const tech=item.technical||{};
      addForecastRow(card,"5 / 20-session historical return",
        (tech.return_5d_pct??"—")+"% / "+(tech.return_20d_pct??"—")+"%");
      addForecastRow(card,"20-session daily volatility / relative volume",
        (tech.volatility_20d_pct??"—")+"% / "+(tech.relative_volume??"—")+"×");
      const review=item.ai_review||{};
      addForecastRow(card,"Selected AI provider review",
        item.ai_review_status==="completed"?
        (review.provider+": sentiment "+review.sentiment+" · impact "+review.impact):
        "Unavailable or not enabled; technical analysis remains independent");
      if(item.ai_review_status==="completed"){
        addForecastRow(card,"AI headline catalyst",review.catalyst||"Not identified");
        addForecastRow(card,"AI headline downside risk",review.downside_risk||"Not identified");
      }
    }else addForecastRow(card,"FinBERT news sentiment",(item.finbert||{}).label||"Unavailable");
    const q=live.status==="fresh" ? (live.symbols||{})[item.ticker] : null;
    addForecastRow(card,"Schwab broker quote",
      q&&q.last ? money(q.last)+" · bid "+money(q.bid||0)+" / ask "+money(q.ask||0):
      "Not available or stale; no live entry confirmation");
    if(q&&q.bid>0&&q.ask>=q.bid){
      addForecastRow(card,"Broker observed bid/ask spread",
        (((q.ask-q.bid)/q.bid)*100).toFixed(2)+"% · observed "+(live.observed_at||""));
    }
    addForecastRow(card,"Above 20-session moving average",item.technical&&item.technical.above_sma20?"Yes":"No");
    const trade=item.entry_scenario||{};
    addForecastRow(card,"Illustrative entry reference",trade.reference_breakout==null?"—":money(trade.reference_breakout));
    addForecastRow(card,"Illustrative risk invalidation",trade.risk_invalidation==null?"—":money(trade.risk_invalidation));
    addForecastRow(card,"Illustrative 2R exit",trade.illustrative_2R_exit==null?"—":money(trade.illustrative_2R_exit));
    const unmet=forecastNode("details");
    unmet.appendChild(forecastNode("summary","Unmet confirmations ("+(item.confirmation_unmet||[]).length+")"));
    const ul=forecastNode("ul");
    (item.confirmation_unmet||[]).forEach(v=>ul.appendChild(forecastNode("li",v)));
    unmet.appendChild(ul);card.appendChild(unmet);
    const news=forecastNode("details");
    news.appendChild(forecastNode("summary","Source-linked news ("+(item.news||[]).length+")"));
    const ol=forecastNode("ol");
    (item.news||[]).forEach(n=>{
      const li=forecastNode("li",(n.source||"Publisher")+": "+(n.title||"Headline")+" ");
      try{
        const u=new URL(n.url);
        if(u.protocol==="https:"&&u.hostname==="news.google.com"){
          const a=forecastNode("a","Read source");
          a.href=u.href;a.target="_blank";a.rel="noopener noreferrer";li.appendChild(a);
        }
      }catch(_){}
      ol.appendChild(li);
    });
    news.appendChild(ol);card.appendChild(news);
    card.appendChild(forecastNode("p",(native?
      "Historical market measurements and heuristic rank, with optional AI commentary. No predictive probabilities or live-order authorization.":
      "Specialized model research only. These are not calibrated probabilities or executable prices."),"panel-note"));
    grid.appendChild(card);
  });
}
document.addEventListener("DOMContentLoaded",()=>{
  const btn=document.getElementById("forecast-refresh");
  if(btn)btn.addEventListener("click",()=>loadForecast().catch(err=>toast(err.message,true)));
});
